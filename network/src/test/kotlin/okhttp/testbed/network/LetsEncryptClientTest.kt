package okhttp.testbed.network

import assertk.assertThat
import assertk.assertions.isEqualTo
import java.security.cert.X509Certificate
import okhttp3.OkHttpClient
import okhttp3.Protocol
import okhttp3.Request
import okhttp3.tls.HandshakeCertificates
import okhttp3.tls.decodeCertificatePem
import org.junit.jupiter.api.Test

/**
 * Confirms a Let's Encrypt server verifies, both against the platform's own trust store and
 * against ISRG Root X1 supplied by the application.
 *
 * The second case is what an app does when it can't rely on the platform having the root — the
 * situation the original Android test was written for, where devices on API 23 and below shipped
 * without it. It stays interesting on the JVM: it verifies the chain the server actually serves
 * today terminates at that root, rather than at whatever else the platform happens to trust.
 *
 * Ported from OkHttp's `android-test`, where it ran as a `Remote` test.
 */
@RequiresEndpoint(Endpoint.LETSENCRYPT)
class LetsEncryptClientTest {
  @Test
  fun getWithPlatformTrustedCertificates() {
    assertRobotsTxt(OkHttpClient())
  }

  @Test
  fun getWithIsrgRootX1() {
    val handshakeCertificates =
      HandshakeCertificates
        .Builder()
        .addTrustedCertificate(ISRG_ROOT_X1)
        .build()

    val client =
      OkHttpClient
        .Builder()
        .sslSocketFactory(
          handshakeCertificates.sslSocketFactory(),
          handshakeCertificates.trustManager,
        ).build()

    assertRobotsTxt(client)
  }

  /**
   * The URL has no `robots.txt`, so 404 is the success case: the response came back, which means
   * the handshake completed.
   */
  private fun assertRobotsTxt(client: OkHttpClient) {
    val request =
      Request
        .Builder()
        .url("https://valid-isrgrootx1.letsencrypt.org/robots.txt")
        .build()
    client.newCall(request).execute().use { response ->
      assertThat(response.code).isEqualTo(404)
      assertThat(response.protocol).isEqualTo(Protocol.HTTP_2)
    }
  }

